using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Semantic.Generator;

[Generator]
public sealed class LocalizationGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "Semantic.Abstractions.LocalizedMessageAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            predicate: static (node, _) => node is ClassDeclarationSyntax,
            transform: static (ctx, _) => ToModel(ctx));

        context.RegisterSourceOutput(declarations, static (spc, model) =>
        {
            if (model is null) return;
            if (model.HasMismatch)
            {
                spc.ReportDiagnostic(Diagnostic.Create(
                    DiagnosticDescriptors.LocalizationParameterMismatch,
                    model.Location,
                    model.Name,
                    model.MismatchDetail));
                return;
            }
            spc.AddSource($"{model.Name}.Localization.g.cs", Emit(model));
        });
    }

    private static LocalizationModel? ToModel(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type) return null;

        var attr = ctx.Attributes.FirstOrDefault();
        if (attr is null || attr.ConstructorArguments.Length < 2) return null;

        var template = attr.ConstructorArguments[0].Value as string;
        if (template is null) return null;

        var parameters = new List<LocalizationParam>();
        foreach (var constant in attr.ConstructorArguments[1].Values)
        {
            if (constant.Value is not string raw) continue;
            var colon = raw.IndexOf(':');
            if (colon < 1 || colon == raw.Length - 1) continue;
            parameters.Add(new LocalizationParam(
                raw.Substring(0, colon).Trim(),
                raw.Substring(colon + 1).Trim()));
        }

        var ns = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();

        var placeholders = new HashSet<string>();
        foreach (Match m in Regex.Matches(template, @"\{(\w+)\}"))
            placeholders.Add(m.Groups[1].Value);

        var paramNames = new HashSet<string>();
        foreach (var p in parameters)
            paramNames.Add(p.Name);

        var mismatches = new List<string>();
        foreach (var ph in placeholders)
            if (!paramNames.Contains(ph))
                mismatches.Add($"placeholder {{{ph}}} is undeclared");
        foreach (var n in paramNames)
            if (!placeholders.Contains(n))
                mismatches.Add($"parameter '{n}' has no placeholder");

        // Replace {name} → {0}, {score} → {1}, etc. by declaration order.
        var formatString = template;
        for (var i = 0; i < parameters.Count; i++)
            formatString = Regex.Replace(
                formatString,
                @"\{" + parameters[i].Name + @"\}",
                "{" + i + "}");

        return new LocalizationModel(
            type.Name,
            ns,
            formatString,
            parameters.ToArray(),
            ctx.TargetNode.GetLocation(),
            mismatches);
    }

    private static string Emit(LocalizationModel model)
    {
        var ns = model.Namespace.Length > 0 ? $"namespace {model.Namespace};\n\n" : string.Empty;

        var paramList = new StringBuilder();
        for (var i = 0; i < model.Parameters.Length; i++)
        {
            if (i > 0) paramList.Append(", ");
            paramList.Append(model.Parameters[i].Type);
            paramList.Append(' ');
            paramList.Append(model.Parameters[i].Name);
        }

        var argList = new StringBuilder();
        for (var i = 0; i < model.Parameters.Length; i++)
        {
            if (i > 0) argList.Append(", ");
            argList.Append(model.Parameters[i].Name);
        }

        return $@"// <auto-generated/>
#nullable enable

{ns}public partial class {model.Name}
{{
    public static string Render({paramList}, global::System.Globalization.CultureInfo? culture = null)
    {{
        culture ??= global::System.Globalization.CultureInfo.CurrentUICulture;
        return string.Format(culture, ""{model.FormatString}"", {argList});
    }}
}}
";
    }

    private sealed class LocalizationModel
    {
        public LocalizationModel(
            string name,
            string ns,
            string formatString,
            LocalizationParam[] parameters,
            Location location,
            List<string> mismatches)
        {
            Name = name;
            Namespace = ns;
            FormatString = formatString;
            Parameters = parameters;
            Location = location;
            HasMismatch = mismatches.Count > 0;
            MismatchDetail = string.Join("; ", mismatches);
        }

        public string Name { get; }
        public string Namespace { get; }
        public string FormatString { get; }
        public LocalizationParam[] Parameters { get; }
        public Location Location { get; }
        public bool HasMismatch { get; }
        public string MismatchDetail { get; }
    }

    private sealed class LocalizationParam
    {
        public LocalizationParam(string type, string name)
        {
            Type = type;
            Name = name;
        }

        public string Type { get; }
        public string Name { get; }
    }
}
