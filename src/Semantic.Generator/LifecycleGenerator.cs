using System.Collections.Generic;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Semantic.Generator;

[Generator]
public sealed class LifecycleGenerator : IIncrementalGenerator
{
    private const string AttributeMetadataName = "Semantic.Abstractions.LifecycleValueAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declarations = context.SyntaxProvider.ForAttributeWithMetadataName(
            AttributeMetadataName,
            predicate: static (node, _) => node is ClassDeclarationSyntax or StructDeclarationSyntax,
            transform: static (ctx, _) => ToModel(ctx));

        context.RegisterSourceOutput(declarations, static (spc, model) =>
        {
            if (model is null) return;
            foreach (var entry in EmitStates(model))
                spc.AddSource(entry.Filename, entry.Source);
        });
    }

    private static LifecycleModel? ToModel(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type) return null;

        var attr = ctx.Attributes.FirstOrDefault();
        if (attr is null || attr.ConstructorArguments.Length < 2) return null;

        var states = attr.ConstructorArguments[0].Values
            .Where(static v => v.Value is string)
            .Select(static v => (string)v.Value!)
            .ToArray();

        var transitions = attr.ConstructorArguments[1].Values
            .Where(static v => v.Value is string)
            .Select(static v => (string)v.Value!)
            .ToArray();

        var ns = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();

        return new LifecycleModel(type.Name, ns, states, transitions);
    }

    private static IEnumerable<(string Filename, string Source)> EmitStates(LifecycleModel model)
    {
        var parsed = ParseTransitions(model.Transitions);

        foreach (var state in model.States)
        {
            var outgoing = parsed.Where(t => t.From == state).ToArray();
            yield return (
                $"{model.Name}{state}Lifecycle.g.cs",
                EmitState(model, state, outgoing)
            );
        }
    }

    private static List<Transition> ParseTransitions(string[] raw)
    {
        var result = new List<Transition>();
        foreach (var t in raw)
        {
            var parts = t.Split(':');
            if (parts.Length == 3)
                result.Add(new Transition(parts[0], parts[1], parts[2]));
        }
        return result;
    }

    private static string EmitState(LifecycleModel model, string state, Transition[] outgoing)
    {
        var ns = model.Namespace.Length > 0 ? $"namespace {model.Namespace};\n\n" : string.Empty;

        var methods = string.Join("\n\n", outgoing.Select(t =>
            $"    public {model.Name}{t.To} {t.Method}() => new {model.Name}{t.To}();"));

        return $@"// <auto-generated/>
#nullable enable

{ns}public sealed class {model.Name}{state}
{{
{methods}
}}
";
    }

    private sealed class LifecycleModel
    {
        public LifecycleModel(string name, string ns, string[] states, string[] transitions)
        {
            Name = name;
            Namespace = ns;
            States = states;
            Transitions = transitions;
        }

        public string Name { get; }
        public string Namespace { get; }
        public string[] States { get; }
        public string[] Transitions { get; }
    }

    private sealed class Transition
    {
        public Transition(string from, string method, string to)
        {
            From = from;
            Method = method;
            To = to;
        }

        public string From { get; }
        public string Method { get; }
        public string To { get; }
    }
}
