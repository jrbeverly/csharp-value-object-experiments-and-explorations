using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Semantic.Generator;

/// <summary>
/// Discovers declarations annotated with <c>[SemanticValue]</c> or
/// <c>[ConstrainedScalar]</c>. The <c>[SemanticValue]</c> pipeline emits the
/// scaffold companion type; the <c>[ConstrainedScalar]</c> pipeline completes
/// constrained scalar declarations with validated construction, parsing,
/// formatting, and equality.
/// </summary>
[Generator]
public sealed class SemanticGenerator : IIncrementalGenerator
{
    private const string SemanticValueAttributeName = "Semantic.Abstractions.SemanticValueAttribute";
    private const string ConstrainedScalarAttributeName = "Semantic.Abstractions.ConstrainedScalarAttribute";

    /// <summary>The only underlying type the constrained scalar track proves.</summary>
    private const SpecialType SupportedUnderlyingType = SpecialType.System_Int32;

    /// <summary>The only constraint kind the constrained scalar track proves (ScalarConstraint.Positive).</summary>
    private const int PositiveConstraint = 0;

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var companions = context.SyntaxProvider.ForAttributeWithMetadataName(
            SemanticValueAttributeName,
            predicate: static (node, _) => node is ClassDeclarationSyntax or StructDeclarationSyntax,
            transform: static (ctx, _) => ToCompanionDeclaration(ctx));

        context.RegisterSourceOutput(companions, static (spc, declaration) =>
        {
            if (declaration is null) return;
            spc.AddSource($"{declaration.Name}Semantic.g.cs", EmitCompanion(declaration));
        });

        var scalars = context.SyntaxProvider.ForAttributeWithMetadataName(
            ConstrainedScalarAttributeName,
            predicate: static (node, _) => node is StructDeclarationSyntax,
            transform: static (ctx, _) => ToScalarDeclaration(ctx));

        context.RegisterSourceOutput(scalars, static (spc, declaration) => EmitScalar(spc, declaration));
    }

    private static CompanionDeclaration? ToCompanionDeclaration(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type) return null;

        var ns = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();

        return new CompanionDeclaration(type.Name, ns);
    }

    private static string EmitCompanion(CompanionDeclaration declaration)
    {
        var ns = declaration.Namespace.Length > 0 ? $"namespace {declaration.Namespace};\n\n" : string.Empty;

        return $@"// <auto-generated/>
#nullable enable

{ns}/// <summary>
/// Companion emitted by Semantic.Generator for the [SemanticValue] declaration
/// <c>{declaration.Name}</c>. Semantic behavior arrives with the tracks.
/// </summary>
public sealed class {declaration.Name}Semantic : global::Semantic.Abstractions.ISemanticValue
{{
    private {declaration.Name}Semantic()
    {{
    }}

    public static {declaration.Name}Semantic Instance {{ get; }} = new {declaration.Name}Semantic();

    public global::Semantic.Runtime.ValidationResult Validate() =>
        global::Semantic.Runtime.ValidationResult.Success();
}}
";
    }

    private static ScalarDeclaration? ToScalarDeclaration(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol type) return null;
        if (ctx.TargetNode is not StructDeclarationSyntax syntax) return null;

        var attribute = ctx.Attributes.FirstOrDefault();
        if (attribute is null || attribute.ConstructorArguments.Length != 2) return null;

        var ns = type.ContainingNamespace.IsGlobalNamespace
            ? string.Empty
            : type.ContainingNamespace.ToDisplayString();

        // Mirror the declaration's modifiers (including 'readonly') so the
        // generated part stays consistent with the authored part.
        var modifiers = string.Join(" ", syntax.Modifiers.Select(m => m.Text));
        var isPartial = syntax.Modifiers.Any(SyntaxKind.PartialKeyword);

        // Argument 0 is typeof(...): a TypedConstant whose Value is the
        // underlying type symbol. Argument 1 is a ScalarConstraint constant,
        // boxed either as the enum instance or its underlying int.
        var underlyingType = attribute.ConstructorArguments[0].Value as INamedTypeSymbol;
        var constraint = attribute.ConstructorArguments[1].Value is null
            ? -1
            : System.Convert.ToInt32(attribute.ConstructorArguments[1].Value);

        var isSupported = underlyingType is not null
            && underlyingType.SpecialType == SupportedUnderlyingType
            && constraint == PositiveConstraint;

        return new ScalarDeclaration(
            type.Name,
            ns,
            modifiers,
            syntax.GetLocation(),
            isPartial,
            isSupported,
            underlyingType?.ToDisplayString());
    }

    private static void EmitScalar(SourceProductionContext spc, ScalarDeclaration? declaration)
    {
        if (declaration is null) return;

        if (!declaration.IsPartial)
        {
            spc.ReportDiagnostic(Diagnostic.Create(
                DiagnosticDescriptors.NotPartialDeclaration,
                declaration.Location,
                declaration.Name));
            return;
        }

        if (!declaration.IsSupported)
        {
            spc.ReportDiagnostic(Diagnostic.Create(
                DiagnosticDescriptors.UnsupportedUnderlyingType,
                declaration.Location,
                declaration.Name,
                declaration.UnderlyingTypeName ?? "<unknown>"));
            return;
        }

        spc.AddSource($"{declaration.Name}.Scalar.g.cs", EmitConstrainedScalar(declaration));
    }

    private static string EmitConstrainedScalar(ScalarDeclaration declaration)
    {
        var name = declaration.Name;
        var ns = declaration.Namespace.Length > 0 ? $"namespace {declaration.Namespace};\n\n" : string.Empty;

        return $@"// <auto-generated/>
#nullable enable

{ns}/// <summary>
/// Constrained scalar emitted by Semantic.Generator for the
/// <c>[ConstrainedScalar(typeof(int), ScalarConstraint.Positive)]</c>
/// declaration <c>{name}</c>. The Positive constraint (<c>value &gt; 0</c>) is
/// enforced at construction and parse boundaries for runtime inputs — it is
/// not a compile-time guarantee, and a default instance bypasses the check.
/// </summary>
{declaration.Modifiers} struct {name} :
    global::System.IEquatable<{name}>,
    global::System.IComparable<{name}>,
    global::Semantic.Abstractions.ISemanticValue
{{
    private readonly int _value;

    /// <summary>Gets the underlying positive integer.</summary>
    public int Value => _value;

    /// <summary>
    /// True when <paramref name=""value""/> satisfies the Positive constraint
    /// (<c>value &gt; 0</c>).
    /// </summary>
    public static bool IsValid(int value) => value > 0;

    /// <summary>Constructs a <see cref=""{name}""/> from <paramref name=""value""/>.</summary>
    /// <exception cref=""global::System.ArgumentOutOfRangeException"">
    /// <paramref name=""value""/> is not positive.
    /// </exception>
    public {name}(int value)
    {{
        if (!IsValid(value))
        {{
            throw new global::System.ArgumentOutOfRangeException(
                nameof(value),
                value,
                ""{name} requires a value greater than zero."");
        }}

        _value = value;
    }}

    /// <summary>
    /// Tries to parse an invariant-culture integer and construct a
    /// <see cref=""{name}""/>. Fails for non-numeric text and non-positive
    /// values.
    /// </summary>
    public static bool TryParse(string? text, out {name} value)
    {{
        if (int.TryParse(
                text,
                global::System.Globalization.NumberStyles.Integer,
                global::System.Globalization.CultureInfo.InvariantCulture,
                out var parsed)
            && IsValid(parsed))
        {{
            value = new {name}(parsed);
            return true;
        }}

        value = default;
        return false;
    }}

    /// <summary>Parses an invariant-culture integer into a <see cref=""{name}""/>.</summary>
    public static global::Semantic.Runtime.ParseResult<{name}> Parse(string? text) =>
        TryParse(text, out var value)
            ? global::Semantic.Runtime.ParseResult<{name}>.Success(value)
            : global::Semantic.Runtime.ParseResult<{name}>.Failure(
                $""'{{text}}' is not a positive integer."");

    public override string ToString() =>
        _value.ToString(global::System.Globalization.CultureInfo.InvariantCulture);

    public bool Equals({name} other) => _value == other._value;

    public override bool Equals(object? obj) => obj is {name} other && Equals(other);

    public override int GetHashCode() => _value;

    public int CompareTo({name} other) => _value.CompareTo(other._value);

    public static bool operator ==({name} left, {name} right) => left.Equals(right);

    public static bool operator !=({name} left, {name} right) => !left.Equals(right);
}}
";
    }

    private sealed class CompanionDeclaration
    {
        public CompanionDeclaration(string name, string ns)
        {
            Name = name;
            Namespace = ns;
        }

        public string Name { get; }

        public string Namespace { get; }
    }

    private sealed class ScalarDeclaration
    {
        public ScalarDeclaration(
            string name,
            string ns,
            string modifiers,
            Location location,
            bool isPartial,
            bool isSupported,
            string? underlyingTypeName)
        {
            Name = name;
            Namespace = ns;
            Modifiers = modifiers;
            Location = location;
            IsPartial = isPartial;
            IsSupported = isSupported;
            UnderlyingTypeName = underlyingTypeName;
        }

        public string Name { get; }

        public string Namespace { get; }

        public string Modifiers { get; }

        public Location Location { get; }

        public bool IsPartial { get; }

        public bool IsSupported { get; }

        public string? UnderlyingTypeName { get; }
    }
}
